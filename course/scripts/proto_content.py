h(2, "5.3  审批中断与恢复")
p("① 用户请求发送邮件，模型返回工具调用；② 执行前挂起，向前端推送审批事件；③ 前端弹出 W3 卡片并锁定输入区；④ 用户确认后调用恢复接口继续执行，取消则结束；⑤ 状态写入检查点，刷新页面或切换会话后卡片按待审批状态重建，不会丢失。")

