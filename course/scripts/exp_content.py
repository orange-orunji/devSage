p("点击左侧栏底部“选择文件上传”，选择 PDF、DOCX、Markdown 或 TXT 文件。系统立即受理并返回任务编号，随后依次完成解析、切分、去重、向量入库与索引重建；处理完成后，工作台统计卡片与“文档管理”页的数字同步更新。")
p("说明：相同内容的文件按 MD5 去重，不会重复入库；单文件建议不超过 50 MB。队列服务不可用时，系统自动转为同步处理，界面提示略有不同但功能不受影响。")
